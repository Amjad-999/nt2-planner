#!/usr/bin/env python3
"""Rebuild the local emoji assets from the registry.

The registry (src/data/emoji/registry.json) is the source of truth. For every
entry this script copies the Twemoji SVG into src/assets/emoji/svg/ and
subsets the Twemoji COLR font down to exactly the registered sequences, then
writes the @font-face rule with a matching unicode-range.

Sources (not vendored, fetch them once into a scratch folder):
    npm pack twemoji-colr-font @twemoji/svg     # then untar both
Usage:
    pip install fonttools brotli
    python3 scripts/build-emoji.py <dir with twemoji.woff2> <dir with the svg files>

Twemoji graphics: (c) Twitter, Inc and other contributors, CC-BY 4.0.
Font build: twemoji-colr-font, SIL OFL 1.1. See src/assets/emoji/LICENSE.md.
"""
import json, os, shutil, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REG = os.path.join(ROOT, 'src/data/emoji/registry.json')
SVG_OUT = os.path.join(ROOT, 'src/assets/emoji/svg')
FONT_OUT = os.path.join(ROOT, 'src/assets/emoji/nt2-emoji.woff2')
CSS_OUT = os.path.join(ROOT, 'src/styles/emoji.css')


def main() -> None:
    font_dir, svg_dir = sys.argv[1], sys.argv[2]
    reg = json.load(open(REG, encoding='utf8'))
    os.makedirs(SVG_OUT, exist_ok=True)
    wanted = set()
    cps = set()
    for e in reg['emoji']:
        seq = [ord(c) for c in e['char']]
        cps.update(seq)
        full = '-'.join(f'{c:x}' for c in seq)
        bare = '-'.join(f'{c:x}' for c in seq if c != 0xFE0F)
        name = next((n for n in (full, bare) if os.path.exists(os.path.join(svg_dir, n + '.svg'))), None)
        if name is None:
            sys.exit(f'no Twemoji artwork for {e["char"]} ({full})')
        target = os.path.basename(e['asset'])
        shutil.copyfile(os.path.join(svg_dir, name + '.svg'), os.path.join(SVG_OUT, target))
        wanted.add(target)
    for f in os.listdir(SVG_OUT):
        if f not in wanted:
            os.remove(os.path.join(SVG_OUT, f))

    text = ''.join(e['char'] for e in reg['emoji'])
    subprocess.run([
        sys.executable, '-m', 'fontTools.subset', os.path.join(font_dir, 'twemoji.woff2'),
        f'--text={text}', '--layout-features=*', '--flavor=woff2', f'--output-file={FONT_OUT}',
        '--no-hinting', '--desubroutinize', '--name-IDs=1,2,3,4,6,13,14',
    ], check=True)

    # unicode-range: the pictographic code points only. Variation selectors,
    # ZWJ and anything ASCII are left out so the face can never capture a
    # digit, a letter or plain punctuation.
    base = sorted(c for c in cps if c not in (0xFE0F, 0x200D) and c > 0xFF)
    rng = ', '.join(f'U+{c:X}' for c in base)
    open(CSS_OUT, 'w', encoding='utf8').write(f'''/* GENERATED by scripts/build-emoji.py — do not edit by hand.
   One local colour-emoji face (Twemoji, COLR/CPAL — vector, any size) holding
   exactly the {len(reg['emoji'])} sequences listed in src/data/emoji/registry.json.
   It sits first in every font stack but its unicode-range names only those
   pictographs, so it draws emoji and nothing else, identically on every
   device. A sequence outside the registry falls through to the system emoji
   font; src/tests/unit/emoji-registry.test.ts fails before that can ship. */
@font-face {{
  font-family: 'NT2 Emoji';
  font-style: normal;
  font-weight: 400;
  font-display: swap;
  src: url('../assets/emoji/nt2-emoji.woff2') format('woff2');
  unicode-range: {rng};
}}
''')
    print(f'{len(reg["emoji"])} emoji · {os.path.getsize(FONT_OUT)} bytes · {len(base)} code points')


if __name__ == '__main__':
    main()
